"""Issue #3: one small cross-domain co-activation probe.

**Model:** pythia-70m-deduped, fp32, CPU, SAE `pythia-70m-deduped-res-sm`,
  hook `blocks.3.hook_resid_post` (d_in=512, d_sae=32768).
**Inputs:** `Corpus/cross_domain.json` - 120 cooking and 120 astronomy
  passages generated by `gen_cross_domain.py`. The two sets share **zero
  tokenizer ids** (verified, not assumed) and each domain has its own glue
  tokens: the strict input-disjointness gate from DEC-011.
**Question:** is there an SAE feature that fires on both a cooking passage and
  an astronomy passage more than chance? Methodology proof-of-concept, not a
  math-discovery attempt.
**Null:** pairing permutation, N_PERM=400. For each family feature, its
  observed matched-pairing co-activation rate is standardized against the
  mean/sd of that same rate over shuffled pairings (equally token-disjoint).
**Correction:** family-wise max-statistic on the **standardized** statistic:
  the 95th percentile, over permutations, of the maximum per-feature z-score
  (DEC-016 family). BH-FDR is not used.
**Issue:** #3 (run 20260919-0229-to3m).

WHY THE STATISTIC IS STANDARDIZED (found by running, DEC-019 applied twice)

  A first version used the raw co-activation RATE with a family-max cutoff.
  Its positive control failed to recover: injecting a rare shared token into
  10% of pairs produced best rate 0.3417 vs cutoff 0.3750. Diagnosing that
  instead of shipping it showed the cutoff was dominated by high-firing-rate
  features, whose chance co-activation is ~0.37 no matter what is injected.
  This is DEC-016's structural failure again in a new place: a family-max over
  a raw rate cannot be cleared by a sparse signal when some family member
  co-fires at ~0.37 by chance.
  The fix is to standardize per feature -- (observed - perm_mean) / perm_sd --
  which puts every feature on the same scale regardless of its firing rate.
  With that single change the same positive control recovers emphatically:
  best z = 11.30 against cutoff z = 4.45, on the injected feature. The real
  run reads best z = 3.10 against the same cutoff -> 0 survivors.
  Both numbers are reported; the raw-rate result is retained as the
  documented failure, not deleted.

CARRY-FORWARD APPLIED (from #6 and the #5 adjudication):

  1. Bounded, pre-specified family (selectivity band in BOTH domains), not the
     full feature x pair product (DEC-024).
  2. Per-feature thresholds, never a pooled percentile (DEC-023).
  3. Passage-length context (median 18-19 tokens; usable features rise with
     context, DEC-023).
  4. Per-feature statistic, because it discriminated in #6 where an unbounded
     max-NPMI did not.
  5. A positive control **verified to recover the selected features before the
     real run is interpreted** (DEC-019). It failed on the first statistic and
     that is why the statistic changed.

CONFOUND CHECKLIST is computed and reported in the results. Unusual activation
is not evidence of correctness - hallucination-like generation and genuine
insight look identical from inside activation statistics alone.
"""
import json
import os

import numpy as np
import torch

MODEL = "pythia-70m-deduped"
SAE_RELEASE = "pythia-70m-deduped-res-sm"
HOOK = "blocks.3.hook_resid_post"
LAYER = 3

BATCH = 32
N_PERM = 400
SEED = 3
SEL_LO, SEL_HI = 0.05, 0.60   # selectivity band; capped so no near-constant feature is in
PER_FEATURE_PCT = 95          # retained to document the failure mode (see below)
CLUSTER_COS = 0.5
PLANT_TOKEN = "Zorblat"
PLANT_RATE = 0.10

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, "Corpus", "cross_domain.json")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "2026-09-19-cross-domain-probe-results.json")


def encode(model, sae, texts):
    out = []
    with torch.no_grad():
        for i in range(0, len(texts), BATCH):
            _, c = model.run_with_cache(texts[i:i + BATCH],
                                        names_filter=lambda n: n == HOOK)
            out.append(sae.encode(c[HOOK]).amax(dim=1).cpu().numpy())
            del c
    return np.concatenate(out, axis=0)


def binarize(fn, rule="gt0"):
    """Firing definition. 'gt0' = positive activation; 'pct{K}' = per-feature
    Kth percentile of that feature's own positives (DEC-023). Both are run;
    the results file reports each so the choice is not silent."""
    d = fn.shape[1]
    if rule == "gt0":
        return fn > 0.0
    if rule.startswith("pct"):
        pct = int(rule[3:])
        thr = np.full(d, np.inf)
        for j in range(d):
            pos = fn[:, j][fn[:, j] > 0]
            if pos.size >= 5:
                thr[j] = np.percentile(pos, pct)
        return fn > thr[None, :]
    raise ValueError(rule)


def select_band(fa, fb, lo=SEL_LO, hi=SEL_HI):
    ra, rb = fa.mean(axis=0), fb.mean(axis=0)
    return np.where((ra >= lo) & (ra <= hi) & (rb >= lo) & (rb <= hi))[0]


def evaluate(bin_a, bin_b, sel, n, rng):
    """Standardized per-feature co-activation z, family-wise max-statistic."""
    A, B = bin_a[:, sel], bin_b[:, sel]
    obs = (A & B).mean(axis=0)
    perm = np.empty((N_PERM, sel.size))
    for p in range(N_PERM):
        perm[p] = (A & B[rng.permutation(n)]).mean(axis=0)
    mu, sd = perm.mean(0), perm.std(0) + 1e-9
    z_obs = (obs - mu) / sd
    z_perm = (perm - mu) / sd
    cutoff = float(np.percentile(z_perm.max(axis=1), 95))
    best_i = int(np.argmax(z_obs))
    surv = np.where(z_obs > cutoff)[0]
    return {
        "n_family": int(sel.size),
        "best_z": float(z_obs.max()), "cutoff_z": cutoff,
        "n_survivors": int(surv.size),
        "survivor_features": [int(sel[i]) for i in surv],
        "survivor_rates": [float(obs[i]) for i in surv],
        "survivor_rates_perm_mean": [float(mu[i]) for i in surv],
        "top_feature": int(sel[best_i]),
        "top_rate": float(obs[best_i]), "top_perm_mean": float(mu[best_i]),
        "raw_best_rate": float(obs.max()),
        "raw_cutoff": float(np.percentile(perm.max(axis=1), 95)),
    }


def cluster_features(sel, Wdec, cos_thr=CLUSTER_COS):
    if sel.size == 0:
        return []
    v = Wdec[sel]
    v = v / v.norm(dim=1, keepdim=True).clamp_min(1e-8)
    cos = (v @ v.T).numpy()
    parent = list(range(len(sel)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for i in range(len(sel)):
        for j in range(i + 1, len(sel)):
            if cos[i, j] >= cos_thr:
                ri, rj = find(i), find(j)
                if ri != rj:
                    parent[rj] = ri
    groups = {}
    for i in range(len(sel)):
        groups.setdefault(find(i), []).append(int(sel[i]))
    return list(groups.values())


def positive_control(model, sae, cook, astro, n):
    """Append a shared rare token to PLANT_RATE of the paired passages in BOTH
    domains and confirm the statistic recovers an injected feature (DEC-019).
    Returns recovery on gt0 and on the per-feature-pct rule."""
    rng = np.random.default_rng(SEED)
    k = max(2, int(PLANT_RATE * n))
    idx = set(rng.choice(n, size=k, replace=False).tolist())
    c2 = [t + f" {PLANT_TOKEN}" if i in idx else t for i, t in enumerate(cook)]
    a2 = [t + f" {PLANT_TOKEN}" if i in idx else t for i, t in enumerate(astro)]
    fc, fa = encode(model, sae, c2), encode(model, sae, a2)
    out = {"n_injected_pairs": k, "plant_rate": PLANT_RATE,
           "injected_feature_by_construction": None, "rules": {}}
    for rule in ("gt0", "pct95"):
        bc, ba = binarize(fc, rule), binarize(fa, rule)
        sel = select_band(bc, ba)
        if sel.size < 2:
            out["rules"][rule] = {"n_family": int(sel.size),
                                  "recovered": False,
                                  "note": "no features in the band"}
            continue
        r = evaluate(bc, ba, sel, n, np.random.default_rng(SEED))
        r["recovered"] = bool(r["n_survivors"] > 0)
        # is the recovered top feature the one the token actually drives?
        c2_idx = sorted(idx)
        inc = np.zeros(n, bool)
        inc[c2_idx] = True
        top = r["top_feature"]
        elev = float(fc[inc, top].mean() - fc[~inc, top].mean())
        r["top_feature_activation_elevation"] = elev
        out["rules"][rule] = r
        if rule == "gt0":
            out["injected_feature_by_construction"] = top if r["recovered"] else None
    return out


def position_check(model, sae, texts, f, n_passages=40):
    """Mean firing position of a feature, to test the shared-position confound."""
    positions = []
    with torch.no_grad():
        for i in range(0, len(texts[:n_passages]), BATCH):
            _, c = model.run_with_cache(texts[i:i + BATCH],
                                        names_filter=lambda n: n == HOOK)
            acts = c[HOOK]
            L = acts.shape[1]
            enc = sae.encode(acts.reshape(-1, acts.shape[-1])).reshape(
                acts.shape[0], L, -1)
            m = enc[:, :, f].numpy()
            for r in range(m.shape[0]):
                p = np.where(m[r] > 0)[0]
                if p.size:
                    positions.append(float(p.mean() / L))
            del c
    return (float(np.mean(positions)) if positions else None, len(positions))


def main():
    from transformer_lens import HookedTransformer
    from sae_lens import SAE

    print("=== issue #3: cross-domain co-activation probe ===")
    d = json.load(open(CORPUS))
    cook, astro = d["cooking"], d["astronomy"]
    n = min(len(cook), len(astro))
    cook, astro = cook[:n], astro[:n]
    print(f"corpus: cooking={len(cook)} astronomy={len(astro)} "
          f"median_tokens={d['meta']['median_tokens']} "
          f"token_disjoint={d['meta']['token_disjoint']}")
    print(f"statistic=standardized per-feature co-activation z; null=pairing "
          f"permutation N_PERM={N_PERM}; correction=family-wise max-statistic")

    model = HookedTransformer.from_pretrained(MODEL, device="cpu")
    sae = SAE.from_pretrained(release=SAE_RELEASE, sae_id=HOOK, device="cpu")
    Wdec = sae.W_dec.detach().cpu()

    print("\nencoding cooking...")
    fc0 = encode(model, sae, cook)
    print("encoding astronomy...")
    fa0 = encode(model, sae, astro)

    print("\n--- positive control (DEC-019: must recover before the real run "
          "is interpreted) ---")
    pc = positive_control(model, sae, cook, astro, n)
    for rule, r in pc["rules"].items():
        if "best_z" in r:
            print(f"  rule={rule:6s} |family|={r['n_family']:5d} best_z={r['best_z']:.2f} "
                  f"cutoff_z={r['cutoff_z']:.2f} recovered={r['recovered']} "
                  f"top_feature={r['top_feature']} top_rate={r['top_rate']:.4f}")
        else:
            print(f"  rule={rule:6s} {r}")

    print("\n--- real run ---")
    results = {}
    for rule in ("gt0", "pct95"):
        bc, ba = binarize(fc0, rule), binarize(fa0, rule)
        sel = select_band(bc, ba)
        print(f"\n  [rule={rule}] firing features: cooking "
              f"{int((bc.mean(0) > 0).sum())} astronomy {int((ba.mean(0) > 0).sum())}"
              f"  |family| (band [{SEL_LO},{SEL_HI}])= {sel.size}")
        if sel.size < 2:
            results[rule] = {"n_family": int(sel.size), "note": "no family"}
            continue
        r = evaluate(bc, ba, sel, n, np.random.default_rng(SEED))
        cl = cluster_features(sel, Wdec)
        r["n_clusters_at_cos_0.5"] = len(cl)
        r["largest_cluster"] = max((len(x) for x in cl), default=0)
        results[rule] = r
        print(f"    best_z={r['best_z']:.2f} cutoff_z={r['cutoff_z']:.2f} "
              f"survivors={r['n_survivors']}")
        print(f"    (raw-rate comparison: best={r['raw_best_rate']:.4f} "
              f"cutoff={r['raw_cutoff']:.4f} - the statistic that failed the "
              f"positive control)")
        print(f"    clusters at cos>={CLUSTER_COS}: {len(cl)} "
              f"(largest {r['largest_cluster']})")

    # ---------------- confound checklist on the gt0 family ----------------
    print("\n--- confound checklist ---")
    conf = {}
    conf["shared_literal_tokens"] = {
        "shared_token_ids": 0,
        "method": "gen_cross_domain.py token-disjointness check (add_special_tokens=False)",
        "fired": False}
    bc, ba = binarize(fc0, "gt0"), binarize(fa0, "gt0")
    sel = select_band(bc, ba)
    conf["feature_splitting"] = {
        "n_family": int(sel.size),
        "n_clusters_at_cos_0.5": len(cluster_features(sel, Wdec)),
        "note": "one coherent structure appearing as several features would "
                "inflate a raw count; the largest cluster is reported above"}
    rc, ra = bc[:, sel].mean(0), ba[:, sel].mean(0)
    conf["catch_all_features"] = {
        "n": int(sel.size),
        "cooking_firing_rate_range": [float(rc.min()), float(rc.max())] if sel.size else None,
        "astronomy_firing_rate_range": [float(ra.min()), float(ra.max())] if sel.size else None,
        "note": f"band already excludes firing rate > {SEL_HI}"}
    if results.get("gt0", {}).get("n_survivors", 0) > 0:
        surv = results["gt0"]["survivor_features"]
        pos = []
        for f in surv[:10]:
            pc_, nc_ = position_check(model, sae, cook, f)
            pa_, na_ = position_check(model, sae, astro, f)
            pos.append({"feature": f, "mean_rel_pos_cooking": pc_,
                        "mean_rel_pos_astronomy": pa_})
        conf["shared_sequence_position"] = {"per_survivor": pos, "fired": "see values"}
        glue = [{"feature": f, "note": "glue tokens disjoint; a shared "
                 "punctuation feature would show as high firing on both glue sets"}
                for f in surv[:10]]
        conf["punctuation_glue_features"] = {"per_survivor": glue, "fired": "manual"}
    else:
        conf["shared_sequence_position"] = {"n_checked": 0, "note": "no survivors"}
        conf["punctuation_glue_features"] = {"n_checked": 0, "note": "no survivors"}
    for k, v in conf.items():
        print(f"  {k}: {json.dumps(v)[:160]}")

    gt0 = results.get("gt0", {})
    pc_gt0 = pc["rules"].get("gt0", {})
    recovered = bool(pc_gt0.get("recovered"))
    survivors = int(gt0.get("n_survivors", 0))
    if not recovered:
        verdict = "null-by-construction-failure"
    elif survivors > 0:
        verdict = "flagged"
    else:
        verdict = "null"
    print("\n=== summary ===")
    print(f"  positive control recovered: {recovered} "
          f"(best_z {pc_gt0.get('best_z')} vs cutoff {pc_gt0.get('cutoff_z')})")
    print(f"  family={gt0.get('n_family')}  survivors={survivors}  "
          f"best_z={gt0.get('best_z')}  cutoff={gt0.get('cutoff_z')}")
    print("  Unusual activation is not evidence of correctness.")
    print(f"  verdict: {verdict}")

    out = {
        "run_id": "20260919-0229-to3m", "issue": 3, "model": MODEL,
        "sae": SAE_RELEASE, "hook": HOOK, "layer": LAYER,
        "corpus": {"n_per_domain": n, "token_disjoint": True,
                   "median_tokens": d["meta"]["median_tokens"],
                   "disjointness_method": "tokenizer id intersection, "
                                          "add_special_tokens=False"},
        "statistic": "standardized per-feature matched-pairing co-activation rate",
        "null_model": f"pairing permutation, N_PERM={N_PERM}",
        "correction": "family-wise max-statistic on the standardized statistic "
                      "(95th pct over permutations of max per-feature z)",
        "selectivity_band": [SEL_LO, SEL_HI],
        "positive_control": pc,
        "real": results,
        "confounds": conf,
        "verdict": verdict,
    }
    with open(OUT, "w") as fh:
        json.dump(out, fh, indent=2)
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
